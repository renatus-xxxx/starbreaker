#!/usr/bin/env python3
"""Bake the static, expensive screens of STAR BREAKER into RLE data:
the full block field, the HUD static strip (normal/demo), and the
GAME OVER / GAME CLEAR panels. Same PackBits format as
title_img.h, decoded by the game's blit_rle.
Usage: gen_opt_images.py src/main.c <out.h>"""
import sys, os
OUT_PATH = sys.argv[2] if len(sys.argv) > 2 else '/tmp/field_img.h'
src_d = open('/home/hatch/workspace/msx/github/starbreaker/tools/gen_title_ideas_d.py').read()
defs = src_d.split("save(style_d_letters")[0]
sys.argv = ['x', sys.argv[1], '/tmp/timg']
g = {'__name__': 'gendefs'}
exec(compile(defs, 'gen_title_ideas_d', 'exec'), g)
Image, ImageDraw = g['Image'], g['ImageDraw']
W = g['W']
pal, BLACK, BG = g['pal'], g['BLACK'], g['BG']
LBLUE, WHITE, PINK, PURPLE, RED, GREEN = g['LBLUE'], g['WHITE'], g['PINK'], g['PURPLE'], g['RED'], g['GREEN']
font_data = g['font_data']

def to_index(img):
    lut = {pal[i]: i for i in range(16)}
    px = img.load()
    return [[lut[px[x, y]] for x in range(256)] for y in range(212)]

# --- scene helpers on indexed grids ---
def new_grid():
    img = g['quantize'](g['base_scene']())
    return to_index(img)

def grid_blank(fill=BLACK):
    return [[fill] * 256 for _ in range(212)]

def rect(gr, x1, y1, x2, y2, c):
    for y in range(y1, y2 + 1):
        for x in range(x1, x2 + 1):
            gr[y][x] = c

def glyph(gr, x, y, ch, fg, bgc, scale):
    gl = font_data[(ord(ch) - 0x20) * 8:(ord(ch) - 0x20) * 8 + 8]
    for r in range(8):
        for cc in range(8):
            col = fg if gl[r] & (0x80 >> cc) else bgc
            rect(gr, x + cc * scale, y + r * scale,
                 x + cc * scale + scale - 1, y + r * scale + scale - 1, col)

def text(gr, x, y, s, fg, bgc, scale):
    step = 8 * scale + (2 if scale > 1 else 1)
    for ch in s:
        glyph(gr, x, y, ch, fg, bgc, scale)
        x += step

def text_width(s, scale):
    return len(s) * (8 * scale) + (len(s) - 1) * (2 if scale > 1 else 1)

def text_c(gr, y, s, fg, bgc, scale):
    text(gr, (256 - text_width(s, scale)) // 2, y, s, fg, bgc, scale)

# --- FIELD: bg + walls + all 65 blocks ---
field = new_grid()
blk_main = [g['YELLOW'], g['ORANGE'], g['PINK'], g['GREEN'], g['CYAN']]
for r in range(5):
    for c in range(13):
        x, y = 11 + c * 18, 40 + r * 13
        rect(field, x, y, x + 15, y + 9, blk_main[r])
        rect(field, x, y, x + 15, y, WHITE)
        rect(field, x, y + 9, x + 15, y + 9, BLACK)

# --- HUD strips (band y=0..15, digits left black) ---
def hud_strip(center, cx):
    gr = grid_blank()
    text(gr, 8, 4, 'SCORE', LBLUE, BLACK, 1)
    text(gr, cx, 4, center, PURPLE, BLACK, 1)
    text(gr, 192, 4, 'LIFE', PINK, BLACK, 1)
    return gr
hudn = hud_strip('BREAKER', 100)
hudd = hud_strip('DEMO', 112)

# --- Panels ---
def panel(msg, col):
    gr = grid_blank()
    rect(gr, 43, 86, 212, 126, BLACK)
    rect(gr, 43, 86, 212, 86, LBLUE); rect(gr, 43, 126, 212, 126, LBLUE)
    rect(gr, 43, 86, 43, 126, LBLUE); rect(gr, 212, 86, 212, 126, LBLUE)
    text_c(gr, 94, msg, col, BLACK, 2)
    text_c(gr, 116, 'SPACE:RETRY  ESC:TITLE', WHITE, BLACK, 1)
    return gr
pover = panel('GAME OVER', RED)
pclear = panel('GAME CLEAR!', GREEN)

def packbits_row(data):
    out = []
    i, n = 0, len(data)
    while i < n:
        run = 1
        while i + run < n and data[i + run] == data[i] and run < 128:
            run += 1
        if run >= 3:
            out += [257 - run, data[i]]
            i += run
        else:
            start = i
            i += run
            while i < n:
                r = 1
                while i + r < n and data[i + r] == data[i] and r < 3:
                    r += 1
                if r >= 3:
                    break
                i += 1
                if i - start >= 128:
                    break
            lit = data[start:i]
            out.append(len(lit) - 1)
            out += lit
    return out

def emit(name, gr, x0, y0, x1, y1):
    w, h = x1 - x0 + 1, y1 - y0 + 1
    assert w % 2 == 0, (name, w)
    flat = []
    raw = 0
    for y in range(y0, y1 + 1):
        row = [gr[y][x] for x in range(x0, x1 + 1)]
        byts = [(row[i] << 4) | row[i + 1] for i in range(0, w, 2)]
        raw += len(byts)
        flat += packbits_row(byts)
    lines = [f'/* {name}: x={x0} y={y0} w={w} h={h} packed={len(flat)} raw={raw} */',
             f'#define {name}_X {x0}', f'#define {name}_Y {y0}',
             f'#define {name}_WB {w // 2}', f'#define {name}_H {h}',
             f'static const unsigned char {name.lower()}_data[{len(flat)}] = {{']
    for i in range(0, len(flat), 16):
        lines.append('    ' + ','.join(str(b) for b in flat[i:i + 16]) + ',')
    lines.append('};')
    print(f'{name}: packed={len(flat)} raw={raw}')
    return '\n'.join(lines)

parts = ['/* generated by tools/gen_opt_images.py - do not edit */\n'
         '#ifndef FIELD_IMG_H\n#define FIELD_IMG_H\n']
# the field is baked as five row bands so the stage intro can
# cascade them in (see build_intro in main.c)
for r in range(5):
    parts.append(emit('TFIELDR%d' % r, field, 10, 39 + r * 13, 245, 39 + r * 13 + 12))
parts.append('static const unsigned char *const tfield_bands[5] = {\n'
             '    tfieldr0_data, tfieldr1_data, tfieldr2_data,\n'
             '    tfieldr3_data, tfieldr4_data\n};')
parts.append(emit('THUDN', hudn, 0, 0, 255, 15))
parts.append(emit('THUDD', hudd, 0, 0, 255, 15))
# panels: the message/hint text is wider than the frame and
# overflows on both sides (as in the original glyph rendering);
# bake the overflow strips too so nothing is clipped.
for nm, gr in (('TPOVER', pover), ('TPCLEAR', pclear)):
    parts.append(emit(nm, gr, 42, 86, 213, 126))
    parts.append(emit(nm + 'L', gr, 26, 92, 41, 125))
    parts.append(emit(nm + 'R', gr, 214, 92, 227, 125))
parts.append('\n#endif\n')
open(OUT_PATH, 'w').write('\n\n'.join(parts))
print('wrote', OUT_PATH)
